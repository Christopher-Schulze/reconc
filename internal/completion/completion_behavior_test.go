package completion

import (
	"bytes"
	"fmt"
	"os/exec"
	"strings"
	"testing"
)

func TestBashCompletesPartiallyTypedValues(t *testing.T) {
	var generated bytes.Buffer
	if err := GenerateBash(&generated); err != nil {
		t.Fatal(err)
	}
	tests := []struct {
		name, words, want string
		current           int
	}{
		{name: "direct positional", words: "reconc completion b", current: 2, want: "bash"},
		{name: "nested positional", words: "reconc hook generate c", current: 3, want: "claude-code"},
		{name: "direct flag value", words: "reconc check --format j", current: 3, want: "json"},
		{name: "nested flag value", words: "reconc bootstrap plan --profile g", current: 4, want: "governed"},
		{name: "third-level flag", words: "reconc repo sync plan --j", current: 4, want: "--json"},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			script := generated.String() + fmt.Sprintf("\nvalues=unrelated flags=--unrelated\nCOMP_WORDS=(%s)\nCOMP_CWORD=%d\n_reconc\nprintf '%%s\\n' \"${COMPREPLY[@]}\"\n", test.words, test.current)
			command := exec.Command("bash", "--noprofile", "--norc")
			command.Stdin = strings.NewReader(script)
			output, err := command.CombinedOutput()
			if err != nil {
				t.Fatalf("execute completion: %v\n%s", err, output)
			}
			if !strings.Contains("\n"+string(output), "\n"+test.want+"\n") {
				t.Fatalf("partial word did not complete to %q: %s", test.want, output)
			}
		})
	}
}
